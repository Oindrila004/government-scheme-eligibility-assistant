
-- 1. User accounts
CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. User profiles
CREATE TABLE IF NOT EXISTS user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE NOT NULL REFERENCES app_user(id),
    date_of_birth DATE,
    state VARCHAR(100),
    annual_income NUMERIC(12,2),
    occupation VARCHAR(100)
);

-- 3. Government schemes
CREATE TABLE IF NOT EXISTS scheme (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_name VARCHAR(255) NOT NULL,
    description TEXT,
    state_scope VARCHAR(100) DEFAULT 'ALL_INDIA',
    official_url TEXT,
    status VARCHAR(30) DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. Eligibility rules
CREATE TABLE IF NOT EXISTS eligibility_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL REFERENCES scheme(id),
    rule_type VARCHAR(100) NOT NULL,
    rule_definition JSONB NOT NULL
);

-- 5. Official scheme documents
CREATE TABLE IF NOT EXISTS scheme_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scheme_id BIGINT NOT NULL REFERENCES scheme(id),
    file_name VARCHAR(255) NOT NULL,
    storage_key TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. User uploaded documents
CREATE TABLE IF NOT EXISTS user_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    file_name VARCHAR(255) NOT NULL,
    storage_key TEXT,
    upload_status VARCHAR(50) DEFAULT 'PENDING',
    uploaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 7. Eligibility assessments
CREATE TABLE IF NOT EXISTS eligibility_assessment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 8. Assessment results
CREATE TABLE IF NOT EXISTS assessment_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL
        REFERENCES eligibility_assessment(id),
    scheme_id BIGINT NOT NULL REFERENCES scheme(id),
    eligibility_status VARCHAR(30) NOT NULL,
    explanation TEXT,
    UNIQUE (assessment_id, scheme_id)
);

-- Useful indexes
CREATE INDEX IF NOT EXISTS idx_scheme_status
    ON scheme(status);

CREATE INDEX IF NOT EXISTS idx_eligibility_rule_scheme
    ON eligibility_rule(scheme_id);

CREATE INDEX IF NOT EXISTS idx_assessment_user
    ON eligibility_assessment(user_id);